export function lookupLexicon(word) {
  const raw = String(word || "").trim();
  if (!raw) return null;
  const lower = raw.toLowerCase().replace(/[^a-z'-]/g, "");
  const stem = lower.replace(/(eth|est|ing|ied|ies|ed|es|s|ly)$/i, (m, _s, offset, str) =>
    str.length - m.length >= 3 ? "" : m
  );
  const hit = STRONGS[lower] || STRONGS[stem];
  if (hit) {
    const orig = String(hit.original || "");
    const translit = (orig.match(/\(([^)]+)\)/) || [])[1] || "";
    return { query: raw, ...hit, translit };
  }
  for (const [k, entry] of Object.entries(STRONGS)) {
    if (entry.forms?.includes(lower) || entry.forms?.includes(stem)) {
      const orig = String(entry.original || "");
      const translit = (orig.match(/\(([^)]+)\)/) || [])[1] || "";
      return { query: raw, ...entry, translit, matchedForm: k };
    }
  }
  return null;
}
